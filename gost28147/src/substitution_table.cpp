bool SubstitutionTable::is_valid() const {
    for (const auto& node : rows_) {
        std::array<bool, 16> seen{};
        for (std::uint8_t v : node) {
            if (v > 15 || seen[v]) {
                return false;
            }
            seen[v] = true;
        }
    }
    return true;
}

