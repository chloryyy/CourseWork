def add_paragraph_text(doc, text, first_line_indent=True, bold=False, alignment=WD_ALIGN_PARAGRAPH.JUSTIFY):
    """Добавить абзац текста."""
    p = doc.add_paragraph()
    p.alignment = alignment
    if first_line_indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    run = p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.font.bold = bold
    return p


def add_heading_text(doc, text, level=1):
    """Добавить заголовок."""
    heading = doc.add_heading(text, level=level)
    # Fix font for all runs in heading
    for run in heading.runs:
        run.font.name = 'Times New Roman'
        run.font.color.rgb = RGBColor(0, 0, 0)
    return heading


